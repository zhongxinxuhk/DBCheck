def core_family(db_type):
    name = str(db_type or '').lower().removesuffix('_jdbc').removesuffix('_full')
    return {'dm8': 'dm', 'mssql': 'sqlserver'}.get(name, name)


def field_description(db_type, sql, field):
    family = core_family(db_type)
    if family == 'gbase8a' and re.match(r'grants for\b', field, re.I):
        return '当前账号的授权语句'
    if family == 'sqlserver' and field.upper() in ('LOGDATE', 'PROCESSINFO'):
        if 'SP_READERRORLOG' not in sql.upper() and 'XP_READERRORLOG' not in sql.upper():
            return ''
    return _FIELDS.get(family, {}).get(field.upper(), '')


def metric_label(db_type, sql, column, value, baseline_descriptions=None):
    """Annotate identifiers only in known parameter, statistic and event columns."""
    family = core_family(db_type)
    if family not in VENDOR_REFERENCES or not isinstance(value, str) or not value.strip():
        return value
    if re.search(r'[\u4e00-\u9fff]', value):
        return value
    source = sql.upper()
    field = column.lower()
    key = value.strip().lower()
    if field in {'name', 'variable_name', 'parameter', 'para_name', 'p_name'} and (
        re.search(r'\bSHOW\s+(?:(?:GLOBAL|SESSION)\s+)?VARIABLES\b', source)
        or any(token in source for token in ('V$PARAMETER', 'V$SYSTEM_PARAMETER', 'V$DM_INI',
                                               'SYS.CONFIGURATIONS', 'V$INI'))
    ):
        description = _PARAMETERS.get(family, {}).get(key, '')
        if not description and baseline_descriptions:
            description = baseline_descriptions.get(key, '')
        description = description or '厂商配置参数，取值含义依对应版本参数手册'
    elif field in {'event', 'event_name', 'wait_type'} and any(
        token in source for token in ('V$SESSION', 'V$SYSTEM_EVENT', 'DM_OS_WAIT_STATS', 'DM_EXEC_REQUESTS')
    ):
        description = _EVENTS.get(family, {}).get(key, '')
        description = description or '厂商等待事件，需结合等待类别和时长解读'
    elif field in {'name', 'variable_name', 'stat_name', 'statname', 'counter_name'} and (
        re.search(r'\bSHOW\s+(?:(?:GLOBAL|SESSION)\s+)?STATUS\b', source)
        or any(token in source for token in ('V$SYSSTAT', 'V$STATNAME', 'DM_OS_PERFORMANCE_COUNTERS'))
    ):
        description = _STATISTICS.get(family, {}).get(key, '')
        if family == 'gbase8a' and key.startswith('com_') and not description:
            description = f'{value[4:].replace("_", " ").upper()} 命令累计执行次数'
        description = description or '厂商运行统计项，单位和采样口径依对应版本手册'
    else:
        return value
    return f'{value}（{description}）'
